import type { ExamDoc, ExamPart, ExamQuestion, PrepDoc } from "@/lib/exams-types";

let n = 0;
const nid = (p: string) => `${p}${++n}`;

function q(text: string, points: number | null, subs: string[] = [], footer = ""): ExamQuestion {
  return {
    id: nid("q"),
    text,
    points,
    footer,
    rubric: "",
    subs: subs.map((s) => ({ id: nid("s"), text: s, points: null, rubric: "" })),
  };
}

function part(
  title: string,
  points: number,
  instructions: string,
  answerCount: number | null,
  questions: ExamQuestion[]
): ExamPart {
  return { id: nid("p"), title, instructions, points, answerCount, questions };
}

