export function findEssay(key: string): EssayExercise | null {
  return ESSAY_EXERCISES.find((e) => e.key === key) ?? null;
}

// a plain reading of the source, for Claude's evaluation prompt
export function essaySourceText(e: EssayExercise): string {
  return `${e.source.title}\n${e.source.paragraphs.join("\n\n")}`;
}

export const ESSAY_WORD_COUNT = (s: string) => (s.trim() ? s.trim().split(/\s+/).length : 0);
