// Full argumentative-writing practices: ~40 minutes each, independent of the
// chapters. A student reads one text, takes it apart, takes a stand, builds
// the case, meets the other side, and writes a whole paragraph. The runner
// (components/writing/essay-runner.tsx) is the same for every practice; what
// changes is the text, the stands and the hints. Every text here is original,
// written for the site (no quoted newspaper columns).

export interface EssaySource {
  title: string;
  byline: string; // who "wrote" it and where — fictional, labelled as such
  paragraphs: string[];
}

export interface EssayExercise {
  kind: "essay";
  key: string;
  title: string;
  flavor: string;
  why: string;
  minutes: number; // recommended total, shown on the card and the timer
  question: string; // the question the student must take a stand on
  source: EssaySource;
  // step 2 — taking the text apart: hints shown under each field
  analysisHints: { claim: string; reasons: string; assumption: string };
  // step 3 — three ways to stand (agree / disagree / in between), phrased for this topic
  stands: string[];
  // step 4 — a nudge toward evidence from the student's own world
  lifeHint: string;
  // step 5 — the other side
  counterHint: string;
  minWords: number; // the whole paragraph, step 6
}

