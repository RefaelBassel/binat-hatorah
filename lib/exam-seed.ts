let seq = 0;
const id = (p: string) => `${p}${++seq}`;

function q(text: string, subs: string[], points: number | null, extra?: Partial<ExamQuestion>): ExamQuestion {
  return {
    id: id("q"),
    text,
    points,
    rubric: "",
    subs: subs.map((s) => ({ id: id("s"), text: s, points: null, rubric: "" })),
    ...extra,
  };
}

