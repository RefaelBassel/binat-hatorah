// The earlier breadth-question text (issue #58), recognised as "never edited".
function legacyBreadth(): Map<string, string> {
  const m = new Map<string, string>();
  for (const q of breadthPart().questions) for (const s of q.subs) m.set(`${q.text}||${s.text}`, s.rubric);
  return m;
}

// Fills the marking guide of the seeded exam. A sub-item is filled only when
// its guide is empty or still the earlier sample answer; anything the teacher
// wrote is kept. Returns whether anything changed.
export function applySeedRubrics(body: ExamBody): { body: ExamBody; changed: boolean } {
  const seed = seedExamBody();
  const legacy = legacyBreadth();
  const wanted = new Map<string, string>();
  seed.parts.forEach((p, pi) =>
    p.questions.forEach((q, qi) =>
      q.subs.forEach((s, si) => {
        const text = TEXTS[pi]?.[qi]?.[si];
        if (text) wanted.set(`${q.text}||${s.text}`, text);
      })
    )
  );
  let changed = false;
  const next: ExamBody = {
    parts: body.parts.map((p) => ({
      ...p,
      questions: p.questions.map((q) => ({
        ...q,
        subs: q.subs.map((s) => {
          const key = `${q.text}||${s.text}`;
          const text = wanted.get(key);
          const cur = s.rubric ?? "";
          if (!text || cur === text) return s;
          if (cur.trim() !== "" && cur !== legacy.get(key)) return s;
          changed = true;
          return { ...s, rubric: text };
        }),
      })),
    })),
  };
  return { body: next, changed };
}
