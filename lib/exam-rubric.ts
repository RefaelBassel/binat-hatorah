// Marking guide (מחוון) for the exam "chapters 9-16" (issue #60): for every
// sub-item a sample answer grounded in the verses and the commentators of the
// units, the points split per component, partial credit and common mistakes.
// Teacher-only: it lives in the rubric fields of the exam, which students
// never receive (stripRubric). The teacher edits it in the exam editor.
//
// Shares: part א׳ sub-items are 10/3 each (written 3⅓), part ב׳ 2.5, part ג׳
// 2.5 / 3⅓ / 5, part ד׳ 20 for the chosen topic.

function r(answer: string, points: string, partial?: string, mistakes?: string): string {
  const lines = [`תשובה לדוגמה: ${answer}`, `פירוק הניקוד: ${points}`];
  if (partial) lines.push(`תשובה חלקית: ${partial}`);
  if (mistakes) lines.push(`טעויות נפוצות: ${mistakes}`);
  return lines.join("\n");
}

