// Collects every Hebrew interface string of the student task page (JSX text,
// string literals, the literal parts of template strings) into
// lib/task-ui-strings.ts. The English-language student's page translates
// exactly these strings in the browser. Re-run after changing the task UI:
//   node scripts/extract-task-ui-strings.mjs
import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

const FILES = [
  "components/task/task-runner.tsx",
  "components/task/comprehension-check.tsx",
  "components/task/answer-guard.tsx",
  "components/task/review-feedback.tsx",
  "components/task/thinking-card.tsx",
  "components/task/verse-audio.tsx",
  "components/task/worksheet-slides.tsx",
  "components/writing/essay-runner.tsx",
  "components/reflection-drawer.tsx",
  "content/tasks/registry.ts",
  "app/tasks/[taskId]/page.tsx",
];

const HEB = /[֐-׿]/;
const out = new Set();
const add = (raw) => {
  for (const part of String(raw).split(/\n/)) {
    const t = part.replace(/\s+/g, " ").trim();
    if (t && HEB.test(t) && t.length <= 600) out.add(t);
  }
};

for (const file of FILES) {
  let src;
  try {
    src = readFileSync(file, "utf8");
  } catch {
    continue;
  }
  const sf = ts.createSourceFile(file, src, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const visit = (node) => {
    if (ts.isJsxText(node)) add(node.getText(sf));
    else if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) add(node.text);
    else if (ts.isTemplateExpression(node)) {
      add(node.head.text);
      for (const span of node.templateSpans) add(span.literal.text);
      // the whole template with {} for each expression ("שאלה {} מתוך {}"):
      // the browser layer matches numbers into it
      add(node.head.text + node.templateSpans.map((sp) => "{}" + sp.literal.text).join(""));
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
}

const list = [...out].sort();
writeFileSync(
  "lib/task-ui-strings.ts",
  `// Generated by scripts/extract-task-ui-strings.mjs — do not edit by hand.\n// The Hebrew interface strings of the student task page (${list.length}).\nexport const TASK_UI_STRINGS: readonly string[] = ${JSON.stringify(list, null, 0).replace(/","/g, '",\n  "').replace(/^\[/, "[\n  ").replace(/\]$/, ",\n]")};\n`
);
console.log(`${list.length} strings → lib/task-ui-strings.ts`);
